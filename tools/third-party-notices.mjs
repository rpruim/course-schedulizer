#!/usr/bin/env node
// Writes THIRD-PARTY-NOTICES.md (and a copy the built site serves) from the licenses of the packages
// that are installed for production. Run after `pnpm install` whenever dependencies change:
//     pnpm run notices
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const json = JSON.parse(execFileSync("pnpm", ["licenses", "list", "--prod", "--json"], { cwd: root, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 }));

/** The license text a package ships, if any. */
function licenseText(dir) {
  const names = readdirSync(dir).filter((f) => /^(licen[sc]e|copying|unlicense)(\.|$)/i.test(f)).sort();
  return names.length ? readFileSync(join(dir, names[0]), "utf8").trim() : "";
}

